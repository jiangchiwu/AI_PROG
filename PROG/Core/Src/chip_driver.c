static HAL_StatusTypeDef STM32F1_Wait_Flash_Busy(void)
{
    uint32_t sr;
    uint32_t timeout = 100000;
    
    do {
        DAP_ReadWord(STM32_FLASH_SR_ADDR, &sr);
        if (!(sr & STM32_FLASH_SR_BSY)) {
            return HAL_OK;
        }
        timeout--;
    } while (timeout > 0);
    
    return HAL_TIMEOUT;
}

static HAL_StatusTypeDef STM32F1_Flash_Unlock(void)
{
    // 写入解锁密钥
    DAP_WriteWord(STM32_FLASH_KEYR_ADDR, STM32_FLASH_KEY1);
    DAP_WriteWord(STM32_FLASH_KEYR_ADDR, STM32_FLASH_KEY2);
    return HAL_OK;
}

static HAL_StatusTypeDef STM32F1_Flash_Lock(void)
{
    uint32_t cr;
    DAP_ReadWord(STM32_FLASH_CR_ADDR, &cr);
    cr |= STM32_FLASH_CR_LOCK;
    DAP_WriteWord(STM32_FLASH_CR_ADDR, cr);
    return HAL_OK;
}

HAL_StatusTypeDef STM32F1_Detect(Chip_Info_TypeDef *info)
{
    uint32_t chip_id;
    uint32_t i;

    // STM32F1通过DBGMCU读取芯片ID
    if (DAP_ReadWord(0xE0042000UL, &chip_id) != HAL_OK) {
        return HAL_ERROR;
    }

    // 查找芯片表
    for (i = 0; stm32f1_chips[i].id != 0; i++) {
        if (stm32f1_chips[i].id == chip_id) {
            strcpy(info->name, stm32f1_chips[i].name);
            strcpy(info->vendor, "STMicroelectronics");
            strcpy(info->family, "STM32F1");
            info->chip_id = chip_id;
            info->flash_size = stm32f1_chips[i].flash_size;
            info->ram_size = stm32f1_chips[i].ram_size;
            info->flash_base = STM32_FLASH_BASE;
            info->flash_sector_size = stm32f1_chips[i].sector_size;
            info->flash_sector_count = info->flash_size / info->flash_sector_size;
            info->ram_base = STM32_SRAM_BASE;
            info->has_eeprom = 0;
            info->eeprom_size = 0;
            info->eeprom_base = 0;
            info->has_option_bytes = 1;
            info->has_security = 0;
            info->debug_interface = 1;

            return HAL_OK;
        }
    }

    return HAL_ERROR;
}

HAL_StatusTypeDef STM32F1_Flash_Init(void)
{
    return STM32F1_Flash_Unlock();
}

HAL_StatusTypeDef STM32F1_Flash_Erase_Sector(uint32_t addr)
{
    HAL_StatusTypeDef status;
    uint32_t cr;
    uint32_t sector = (addr - STM32_FLASH_BASE) / g_chip_info.flash_sector_size;
    
    status = STM32F1_Wait_Flash_Busy();
    if (status != HAL_OK) {
        return status;
    }
    
    DAP_ReadWord(STM32_FLASH_CR_ADDR, &cr);
    cr &= ~(STM32_FLASH_CR_PER | STM32_FLASH_CR_MER);
    cr |= STM32_FLASH_CR_PER;
    DAP_WriteWord(STM32_FLASH_CR_ADDR, cr);
    
    DAP_WriteWord(STM32_FLASH_AR_ADDR, STM32_FLASH_BASE + sector * g_chip_info.flash_sector_size);
    
    cr |= (1 << 16);
    DAP_WriteWord(STM32_FLASH_CR_ADDR, cr);
    
    status = STM32F1_Wait_Flash_Busy();
    if (status != HAL_OK) {
        return status;
    }
    
    cr &= ~STM32_FLASH_CR_PER;
    DAP_WriteWord(STM32_FLASH_CR_ADDR, cr);
    
    return HAL_OK;
}

HAL_StatusTypeDef STM32F1_Flash_Write(uint32_t addr, uint8_t *data, uint32_t size)
{
    HAL_StatusTypeDef status;
    uint32_t cr;
    uint32_t i;
    
    for (i = 0; i < size; i += 2) {
        status = STM32F1_Wait_Flash_Busy();
        if (status != HAL_OK) {
            return status;
        }
        
        DAP_ReadWord(STM32_FLASH_CR_ADDR, &cr);
        cr |= STM32_FLASH_CR_PG;
        DAP_WriteWord(STM32_FLASH_CR_ADDR, cr);
        
        uint16_t halfword = data[i];
        if (i + 1 < size) {
            halfword |= (uint16_t)data[i + 1] << 8;
        }
        
        DAP_WriteWord(addr + i, (uint32_t)halfword);
        
        status = STM32F1_Wait_Flash_Busy();
        if (status != HAL_OK) {
            return status;
        }
        
        cr &= ~STM32_FLASH_CR_PG;
        DAP_WriteWord(STM32_FLASH_CR_ADDR, cr);
    }
    
    return HAL_OK;
}

