HAL_StatusTypeDef GD32L2_Flash_Erase_Sector(uint32_t addr)
{
    HAL_StatusTypeDef status;
    uint32_t cr;
    uint32_t sector = (addr - STM32_FLASH_BASE) / g_chip_info.flash_sector_size;
    
    status = GD32L2_Wait_Flash_Busy();
    if (status != HAL_OK) {
        return status;
    }
    
    DAP_ReadWord(STM32_FLASH_CR_ADDR, &cr);
    cr &= ~(0x1F << 3);
    cr |= sector << 3;
    cr |= STM32_FLASH_CR_SER;
    DAP_WriteWord(STM32_FLASH_CR_ADDR, cr);
    
    cr |= (1 << 16);
    DAP_WriteWord(STM32_FLASH_CR_ADDR, cr);
    
    status = GD32L2_Wait_Flash_Busy();
    if (status != HAL_OK) {
        return status;
    }
    
    cr &= ~STM32_FLASH_CR_SER;
    DAP_WriteWord(STM32_FLASH_CR_ADDR, cr);
    
    return HAL_OK;
}

HAL_StatusTypeDef GD32L2_Flash_Write(uint32_t addr, uint8_t *data, uint32_t size)
{
    HAL_StatusTypeDef status;
    uint32_t cr;
    uint32_t i;
    
    for (i = 0; i < size; i += 8) {
        status = GD32L2_Wait_Flash_Busy();
        if (status != HAL_OK) {
            return status;
        }
        
        DAP_ReadWord(STM32_FLASH_CR_ADDR, &cr);
        cr |= STM32_FLASH_CR_PG;
        DAP_WriteWord(STM32_FLASH_CR_ADDR, cr);
        
        uint32_t word_low = 0, word_high = 0;
        for (uint32_t j = 0; j < 4 && (i + j) < size; j++) {
            word_low |= (uint32_t)data[i + j] << (j * 8);
        }
        for (uint32_t j = 4; j < 8 && (i + j) < size; j++) {
            word_high |= (uint32_t)data[i + j] << ((j - 4) * 8);
        }
        
        DAP_WriteWord(addr + i, word_low);
        if (i + 4 < size) {
            DAP_WriteWord(addr + i + 4, word_high);
        }
        
        status = GD32L2_Wait_Flash_Busy();
        if (status != HAL_OK) {
            return status;
        }
        
        cr &= ~STM32_FLASH_CR_PG;
        DAP_WriteWord(STM32_FLASH_CR_ADDR, cr);
    }
    
    return HAL_OK;
}
